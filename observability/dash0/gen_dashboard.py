"""Generate dashboard.yaml (PersesDashboard for Dash0). Run: python3 observability/dash0/gen_dashboard.py"""
import os
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PANELS = [
    ("checkins", "Check-ins per minute, by desk", 'sum by (leadguard_desk_id) (rate(leadguard_checkins_total[2m])) * 60', "TimeSeriesChart"),
    ("scans", "Scans per minute, by booth", 'sum by (leadguard_booth_id) (rate(leadguard_scans_total{outcome="accepted"}[2m])) * 60', "TimeSeriesChart"),
    ("synclag", "Scan → synced lead, p95 (s). SLO: < 30 s", 'histogram_quantile(0.95, sum by (le) (rate(leadguard_scan_sync_lag_seconds_bucket[5m])))', "TimeSeriesChart"),
    ("queue", "Scans waiting on devices (p95 of heartbeats), by booth", 'histogram_quantile(0.95, sum by (le, leadguard_booth_id) (rate(leadguard_scanner_queue_depth_bucket[5m])))', "TimeSeriesChart"),
    ("anomalies", "Integrity anomalies (new, last 15 min), by kind", 'sum by (leadguard_anomaly_kind) (increase(leadguard_anomalies_total[15m]))', "TimeSeriesChart"),
    ("outcomes", "Scan outcomes (accepted / duplicate retry / rejected)", 'sum by (outcome) (rate(leadguard_scans_total[5m])) * 60', "TimeSeriesChart"),
    ("ingest5xx", "Ingest error ratio (writes that must not be lost)", 'sum(rate(http_server_request_duration_seconds_count{service_name="leadguard-ingest", http_response_status_code=~"5.."}[5m])) / sum(rate(http_server_request_duration_seconds_count{service_name="leadguard-ingest"}[5m]))', "TimeSeriesChart"),
    ("latency", "p95 latency by route (s)", 'histogram_quantile(0.95, sum by (le, http_route) (rate(http_server_request_duration_seconds_bucket{service_name=~"leadguard-.*", http_route=~"/api/.*"}[5m])))', "TimeSeriesChart"),
    ("notfound", "Desk searches that found nobody (last 10 min)", 'sum(increase(leadguard_desk_not_found_total[10m]))', "StatChart"),
]


def build():
    panels, items = {}, []
    for i, (pid, title, query, kind) in enumerate(PANELS):
        panels[pid] = {"kind": "Panel", "spec": {
            "display": {"name": title},
            "plugin": {"kind": kind, "spec": {} if kind == "TimeSeriesChart" else {"calculation": "last-number"}},
            "queries": [{"kind": "TimeSeriesQuery", "spec": {"plugin": {"kind": "PrometheusTimeSeriesQuery", "spec": {"query": query}}}}],
        }}
        items.append({"x": (i % 2) * 12, "y": (i // 2) * 8, "width": 12, "height": 8, "content": {"$ref": f"#/spec/panels/{pid}"}})
    return {
        "apiVersion": "perses.dev/v1alpha1", "kind": "PersesDashboard",
        "metadata": {"name": "leadguard-conference-health", "labels": {"dash0.com/id": "leadguard-conference-health"}},
        "spec": {"display": {"name": "LeadGuard: conference health", "description": "Desks, booths, scanners and lead integrity. Built from the metrics LeadGuard emits; see observability/README.md."},
                 "duration": "1h", "refreshInterval": "30s", "panels": panels, "layouts": [{"kind": "Grid", "spec": {"items": items}}]},
    }


if __name__ == "__main__":
    with open(os.path.join(HERE, "dashboard.yaml"), "w") as f:
        f.write("# Dash0 dashboard (PersesDashboard). Generated by gen_dashboard.py; edit there.\n")
        f.write(yaml.safe_dump(build(), sort_keys=False, width=200))
    print("wrote dashboard.yaml")
